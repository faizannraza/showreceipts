// Renders the provenance table for docs/prices.md (S16 → S33 pastes the
// output). Reads src/cost/prices.json and prints GitHub-flavoured Markdown
// to stdout: model, rates of the current window, verified, confidence,
// source, checkedAt, note. Pure formatting — no pricing logic lives here.
import { readFileSync } from 'node:fs';

const table = JSON.parse(readFileSync(new URL('../src/cost/prices.json', import.meta.url), 'utf8'));

/** The open-ended (current) window, else the first listed one. */
function currentWindow(rates) {
  if (!Array.isArray(rates) || rates.length === 0) return null;
  return rates.find((w) => w.until === null || w.until === undefined) ?? rates[0];
}

function fmt(n) {
  return typeof n === 'number' ? String(n) : '—';
}

function cell(s) {
  return s === undefined || s === null || s === '' ? '' : String(s).replace(/\|/g, '\\|');
}

const lines = [];
lines.push(`# Price table (version ${table.version})`);
lines.push('');
lines.push('Generated by `scripts/gen-prices-doc.mjs` from `src/cost/prices.json` — do not edit by hand.');
lines.push('');
lines.push(`All rates are USD per million tokens (\`${table.unit}\`). Dated rows are priced by the UTC calendar day of each call (or \`--as-of\`).`);
lines.push('Cost is API-equivalent and covers only the API calls present in the transcript: WebFetch/WebSearch sub-requests and compaction/title generation are not logged and not counted.');
lines.push('');
lines.push('| model | match | provider | input | output | cacheRead | verified | confidence | source | checked | note |');
lines.push('|---|---|---|---|---|---|---|---|---|---|---|');

for (const [id, row] of Object.entries(table.models)) {
  const match = row.match ?? 'exact';
  let input = '—';
  let output = '—';
  let cacheRead = '—';
  let note = row.note ?? '';
  if (row.aliasOf !== undefined) {
    input = output = cacheRead = `= ${row.aliasOf}`;
  } else if (row.unpriced === true) {
    note = note === '' ? 'unpriced' : note;
  } else {
    const w = currentWindow(row.rates);
    if (w !== null) {
      input = fmt(w.input);
      output = fmt(w.output);
      const defs = table.defaults[row.provider] ?? {};
      cacheRead = w.cacheRead !== undefined ? fmt(w.cacheRead) : defs.cacheRead !== undefined ? `${defs.cacheRead}× input` : '—';
    }
    if (Array.isArray(row.tiers)) {
      const tiers = row.tiers
        .map((t) => `> ${String(t.aboveInputTokens).replace(/\B(?=(\d{3})+(?!\d))/g, ',')}: ${t.input}/${t.output}/${t.cacheRead ?? '—'}`)
        .join('; ');
      note = note === '' ? `tiers ${tiers}` : `${note}; tiers ${tiers}`;
    }
    if (Array.isArray(row.windows)) {
      const windows = row.windows.map((w2) => `${w2.utc} UTC: ${w2.input}/${w2.output}/${w2.cacheRead ?? '—'}`).join('; ');
      note = note === '' ? `off-peak ${windows}` : `${note}; off-peak ${windows}`;
    }
    if (row.speeds !== undefined) {
      const speeds = Object.entries(row.speeds)
        .map(([name, sp]) => `${name} ${sp.input}/${sp.output}`)
        .join('; ');
      note = note === '' ? `speeds ${speeds}` : `${note}; speeds ${speeds}`;
    }
  }
  lines.push(
    `| \`${cell(id)}\` | ${match} | ${row.provider} | ${input} | ${output} | ${cacheRead} | ${row.verified === true ? 'yes' : 'no'} | ${row.confidence ?? ''} | ${cell(row.source)} | ${cell(row.checkedAt)} | ${cell(note)} |`,
  );
}

lines.push('');
process.stdout.write(`${lines.join('\n')}\n`);
